"""Write the performance report: every metric with its FioriVoce number, the platform and build
it was measured on, OpenWhisper's number and where it comes from, the budget, the verdict and
the package that owns a miss.

    python tools/perf/perf_report.py [--out out/perf] [--output <file.md>]

By default it reads out/perf/ and writes out/perf/performance-report.md. The committed
docs/port/performance-report.md is written only from a Windows run (the product's platform):
--output there is refused when any number was measured elsewhere, unless --allow-non-windows.
"""
from __future__ import annotations

import argparse
import math
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import perf_lib  # noqa: E402

COMMITTED_REPORT = perf_lib.REPO / "docs" / "port" / "performance-report.md"


def fmt(value, unit: str = "") -> str:
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return "-"
    if unit == "widgets":
        return f"{value:.0f}"
    if unit == "s":
        return f"{value:.3f}"
    return f"{value:.2f}" if abs(value) < 100 else f"{value:.1f}"


def budget_text(verdict: perf_lib.Verdict, budget: dict | None) -> str:
    if budget is None or verdict.compare == "info":
        return "-"
    if verdict.compare == "max":
        return f"<= {fmt(budget['budget'], verdict.unit)} {verdict.unit}"
    ratio = budget["budget"]
    times = "" if ratio == 1 else f"{ratio:g} x "
    if verdict.limit is None:
        return f"<= {times}OpenWhisper"
    return f"<= {times}OpenWhisper ({fmt(verdict.limit, verdict.unit)} {verdict.unit})"


def reference_text(verdict: perf_lib.Verdict, unavailable: dict[str, str]) -> str:
    reference = verdict.reference
    if reference and isinstance(reference.get("value"), (int, float)):
        kind = "measured" if reference.get("kind") == "measured" else "document"
        return f"{fmt(reference['value'], verdict.unit)} ({kind})"
    if verdict.metric in unavailable:
        return "none"
    return "-"


def measured_on(record: dict | None) -> str:
    if not record:
        return "-"
    machine = record.get("machine") or {}
    platform = str(machine.get("platform", "unknown"))
    build = record.get("build", "?")
    return f"{platform.capitalize()}, {build}"


def render(verdicts: list[perf_lib.Verdict], budgets: list[dict], baseline: dict) -> str:
    by_name = {budget["metric"]: budget for budget in budgets}
    unavailable = baseline.get("unavailable", {})
    records = [verdict.record for verdict in verdicts if verdict.record]
    platforms = Counter(perf_lib.platform_of(record) for record in records)
    builds = Counter(str(record.get("build", "?")) for record in records)
    commits = Counter(str(record.get("commit", "unknown")) for record in records)
    machines = {}
    for record in records:
        machine = record.get("machine") or {}
        key = (machine.get("platform"), machine.get("os"), machine.get("cpu"),
               machine.get("logical_cores"), machine.get("label"))
        machines[key] = machine

    lines = ["# Performance report", ""]
    lines.append("Generated by `tools/perf/perf_report.py` from `out/perf/`. Budgets: "
                 "`tools/perf/budgets.json`; OpenWhisper's numbers: "
                 "`tools/perf/baseline-openwhisper.json` (its committed documents) or "
                 "`out/perf/openwhisper-measured.json` (measured under lead decision 5).")
    lines.append("")
    non_windows = sorted(platform for platform in platforms if platform != "windows")
    if not records:
        lines += ["**Nothing was measured.** Run `python tools/perf/run_perf.py` first.", ""]
    elif non_windows:
        lines += [
            f"> **Measured on {', '.join(p.capitalize() for p in non_windows)}, not Windows.** "
            "FioriVoce is a Windows product; these numbers come from another platform and are "
            "not the product's numbers. They show the harness works and how the code behaves "
            "there; the budgets' verdicts below hold for this platform only. The committed "
            "report is the owner's Windows run (tools/perf/README.md).", ""]
    if any(build.lower() == "debug" for build in builds):
        lines += ["> **Debug build.** Some numbers were measured on an unoptimised build; a "
                  "release preset's numbers are the ones budgets are meant for.", ""]

    lines.append("## Where the numbers were measured")
    lines.append("")
    lines.append("| Platform | OS | CPU | Logical cores | Builds | Commits |")
    lines.append("|---|---|---|---|---|---|")
    for machine in machines.values():
        lines.append(f"| {str(machine.get('platform', '?')).capitalize()} "
                     f"| {machine.get('os', '?')} | {machine.get('cpu', '?')} "
                     f"| {machine.get('logical_cores', '?')} "
                     f"| {', '.join(sorted(builds))} "
                     f"| {', '.join(commit[:12] for commit in sorted(commits))} |")
    if not machines:
        lines.append("| - | - | - | - | - | - |")
    lines.append("")

    counts = Counter(verdict.status for verdict in verdicts)
    lines.append("## Summary")
    lines.append("")
    lines.append(", ".join(f"{counts.get(status, 0)} {status}" for status in (
        perf_lib.PASS, perf_lib.MISS, perf_lib.NO_REFERENCE, perf_lib.INFO,
        perf_lib.NOT_MEASURED)) + ".")
    lines.append("")
    missed = perf_lib.misses(verdicts)
    if missed:
        lines.append("Misses, each fixed by its owner package:")
        lines.append("")
        for verdict in missed:
            lines.append(f"- `{verdict.metric}`: {fmt(verdict.value, verdict.unit)} "
                         f"{verdict.unit} against {fmt(verdict.limit, verdict.unit)} "
                         f"{verdict.unit} ({verdict.platform}); owner {verdict.owner}")
        lines.append("")

    lines.append("## Metrics")
    lines.append("")
    lines.append("| Metric | Statistic | FioriVoce | Measured on | OpenWhisper | Budget | Result "
                 "| Owner |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for verdict in verdicts:
        value = fmt(verdict.value, verdict.unit)
        if value != "-":
            value += f" {verdict.unit}"
        samples = len((verdict.record or {}).get("samples", []))
        if samples:
            value += f" (n={samples})"
        result = verdict.status
        if verdict.status == perf_lib.MISS:
            result = "**miss**"
        lines.append(f"| `{verdict.metric}` | {verdict.statistic} | {value} "
                     f"| {measured_on(verdict.record)} "
                     f"| {reference_text(verdict, unavailable)} "
                     f"| {budget_text(verdict, by_name.get(verdict.metric))} "
                     f"| {result} | {verdict.owner} |")
    lines.append("")

    lines.append("## Sources")
    lines.append("")
    for verdict in verdicts:
        budget = by_name.get(verdict.metric)
        if budget is None:
            continue
        parts = [f"budget: {budget['source']}"]
        reference = verdict.reference
        if reference and reference.get("source"):
            parts.append(f"OpenWhisper ({reference.get('kind', 'document')}): "
                         f"{reference['source']}")
        elif verdict.metric in unavailable:
            parts.append(f"OpenWhisper: none ({unavailable[verdict.metric]})")
        if budget.get("note"):
            parts.append(f"note: {budget['note']}")
        lines.append(f"- `{verdict.metric}`: " + "; ".join(parts))
    lines.append("")
    lines.append("Cold and warm numbers are kept apart, as OpenWhisper's document keeps them; "
                 "gains measured separately overlap and do not add up.")
    lines.append("")
    return "\n".join(lines)


def write_report(out: Path, output: Path, allow_non_windows: bool = False) -> Path:
    budgets = perf_lib.load_budgets()
    baseline = perf_lib.read_json(perf_lib.BASELINE_FILE) if perf_lib.BASELINE_FILE.is_file() \
        else {}
    references = perf_lib.load_baseline(perf_lib.BASELINE_FILE, out)
    measured = perf_lib.load_measured(out)
    verdicts = perf_lib.evaluate(budgets, references, measured)
    if output.resolve() == COMMITTED_REPORT.resolve() and not allow_non_windows:
        elsewhere = sorted({perf_lib.platform_of(record) for record in measured.values()} -
                           {"windows"})
        if elsewhere:
            raise SystemExit(f"Refusing to write {COMMITTED_REPORT.relative_to(perf_lib.REPO)} "
                             f"from numbers measured on {', '.join(elsewhere)}: the committed "
                             "report is the Windows run. Write it under out/perf instead.")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render(verdicts, budgets, baseline), encoding="utf-8")
    return output


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", type=Path, default=perf_lib.DEFAULT_OUT,
                        help="the folder of measured metrics (default out/perf)")
    parser.add_argument("--output", type=Path, help="the report (default <out>/performance-report.md)")
    parser.add_argument("--allow-non-windows", action="store_true",
                        help="allow writing docs/port/performance-report.md from non-Windows numbers")
    args = parser.parse_args(argv)
    output = args.output or args.out / "performance-report.md"
    written = write_report(args.out, output, args.allow_non_windows)
    print(f"perf_report: wrote {written}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
