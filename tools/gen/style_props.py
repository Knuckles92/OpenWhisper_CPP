"""Write src/ui_theme/style_props.h: one constant per dynamic property the theme selects on.

    python -I -B tools/gen/style_props.py [--check]

The names are every [property] that a selector of src/ui_theme/resources/theme.qss (OpenWhisper's
sheet, copied unchanged) names, read the way tools/lint/check_qss_names.py reads them, plus the
properties the widgets of the a02 map set without a selector naming them and the internal ones
the theme pipeline keeps on widgets. Widget code passes these constants to
fv::ui::setStyleProperty, so a misspelt property is a compile error instead of a rule that
silently stops matching (architecture 8.4). --check compares with the committed header instead
of writing it and fails on a difference. Only the standard library and this repository are
used.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools" / "lint"))
import check_qss_names  # noqa: E402

SHEET = ROOT / "src" / "ui_theme" / "resources" / "theme.qss"
OUTPUT = ROOT / "src" / "ui_theme" / "style_props.h"

# Set by widgets although no selector of theme.qss names them: "checked" by a02 widgets (a02
# map, "Data and formats"), "unset" by the walkthrough tab's key chips, which a sheet local to
# that tab selects on (walkthrough_tab.py, QLabel#walkthroughKey[unset="true"]).
WIDGET_PROPERTIES = ("checked", "unset")
# Kept on widgets by the theme pipeline and the shell, never selected on.
INTERNAL_PROPERTIES = {
    "unscaledStyleSheet": "the token source of a widget-local sheet (setLocalStyleSheet)",
    "scaledStyleSheet": "the sheet last resolved from unscaledStyleSheet",
    "fiorivoceHotkeyWindow": "marks a top-level window the in-app hotkeys belong to",
}

CXX_KEYWORDS = {
    "alignas", "alignof", "and", "asm", "auto", "bool", "break", "case", "catch", "char",
    "class", "const", "constexpr", "continue", "default", "delete", "do", "double", "else",
    "enum", "explicit", "export", "extern", "false", "float", "for", "friend", "goto", "if",
    "inline", "int", "long", "mutable", "namespace", "new", "not", "nullptr", "operator", "or",
    "private", "protected", "public", "register", "return", "short", "signed", "sizeof",
    "static", "struct", "switch", "template", "this", "throw", "true", "try", "typedef",
    "typeid", "typename", "union", "unsigned", "using", "virtual", "void", "volatile", "while",
    "xor",
}

HEADER = """\
// Generated by tools/gen/style_props.py from src/ui_theme/resources/theme.qss. Do not edit.
#pragma once

#include <QVariant>

class QWidget;

namespace fv::ui {

// Dynamic properties the theme selects on ([tone="danger"]), and the internal ones the theme
// pipeline keeps on widgets. Set them only through setStyleProperty (lint.style_props).
namespace prop {
@constants@
} // namespace prop

// Restyles widget so property selectors match its current values: unpolish, polish, update.
void repolish(QWidget* widget);

// Sets a property a stylesheet selects on, then repolishes. An unchanged value is left alone,
// because repolishing re-matches the whole stylesheet.
void setStyleProperty(QWidget* widget, const char* prop, const QVariant& value);

} // namespace fv::ui
"""


def theme_properties() -> list[str]:
    text = check_qss_names.selectors(SHEET.read_text(encoding="utf-8"))
    return sorted(set(check_qss_names.PROPERTY.findall(text)))


def render() -> str:
    selected = theme_properties()
    lines = []
    for name in sorted(set(selected) | set(WIDGET_PROPERTIES)):
        lines.append(constant(name))
    lines.append("")
    lines.append("// Internal: never selected on.")
    for name, why in INTERNAL_PROPERTIES.items():
        if name in selected:
            raise SystemExit(f"{name} is selected on by theme.qss; it is not internal")
        lines.append(f"// {why[0].upper()}{why[1:]}.")
        lines.append(constant(name))
    return HEADER.replace("@constants@", "\n".join(lines))


def constant(name: str) -> str:
    if not re.fullmatch(r"[A-Za-z_]\w*", name) or name in CXX_KEYWORDS:
        raise SystemExit(f"The property {name!r} cannot be a C++ identifier")
    # The pointer form is the one lint.style_props reads declarations in.
    return f'inline constexpr const char* {name} = "{name}";'


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true",
                        help="compare with the committed header instead of writing it")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if current != text:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date; run tools/gen/style_props.py")
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is up to date")
        return 0
    OUTPUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
