"""Write fv_bench's generated data: the NFKC tables and the cleanup-level golden set.

    python3.12 -I -B tools/gen/bench_data.py [--check]

src/bench/detail/nfkc_tables.inc holds what unicodedata.normalize("NFKC", ...) needs, read back
from the running interpreter's unicodedata: each code point's full compatibility decomposition
(Hangul syllables are algorithmic and left out), the non-zero canonical combining classes, and
the primary composites as (first, second) -> composite pairs. Run it with Python 3.12, whose
unicodedata.unidata_version is 15.0.0, as OpenWhisper's; another version is refused.

src/bench/data/cleanup_golden.jsonl is OpenWhisper's benchmarks/cleanup_levels/golden.jsonl,
copied byte for byte from the checkout OPENWHISPER_CPP_OW_ROOT names (read only, nothing imported).

--check compares with the committed files instead of writing them, and fails on a difference.
"""

from __future__ import annotations

import argparse
import os
import sys
import unicodedata
from pathlib import Path

EXPECTED_UNIDATA = "15.0.0"
ROOT = Path(__file__).resolve().parents[2]
NFKC_OUTPUT = ROOT / "src" / "bench" / "detail" / "nfkc_tables.inc"
GOLDEN_OUTPUT = ROOT / "src" / "bench" / "data" / "cleanup_golden.jsonl"
GOLDEN_SOURCE = Path("benchmarks") / "cleanup_levels" / "golden.jsonl"
HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3


def nfkc_tables() -> str:
    decompositions: list[tuple[int, list[int]]] = []
    classes: list[tuple[int, int]] = []
    compositions: list[tuple[int, int, int]] = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        char = chr(cp)
        if not HANGUL_FIRST <= cp <= HANGUL_LAST:
            nfkd = unicodedata.normalize("NFKD", char)
            if nfkd != char:
                decompositions.append((cp, [ord(c) for c in nfkd]))
        ccc = unicodedata.combining(char)
        if ccc:
            classes.append((cp, ccc))
        raw = unicodedata.decomposition(char)
        if raw and not raw.startswith("<"):
            parts = [int(part, 16) for part in raw.split()]
            # A primary composite: a canonical pair NFC recomposes (not excluded, not a
            # non-starter decomposition).
            if len(parts) == 2 and unicodedata.normalize("NFC", unicodedata.normalize("NFD", char)) == char:
                compositions.append((parts[0], parts[1], cp))
    compositions.sort()
    pool: list[int] = []
    rows = []
    for cp, seq in decompositions:
        rows.append(f"    {{0x{cp:X}, {len(pool)}, {len(seq)}}},")
        pool.extend(seq)
    lines = [
        "// Generated by tools/gen/bench_data.py from Python's unicodedata "
        f"{unicodedata.unidata_version}. Do not edit.",
        "// clang-format off",
        "inline constexpr std::uint32_t kDecompositionPool[] = {",
    ]
    for start in range(0, len(pool), 12):
        lines.append("    " + " ".join(f"0x{v:X}," for v in pool[start:start + 12]))
    lines.append("};")
    lines.append("inline constexpr Decomposition kDecompositions[] = {")
    lines.extend(rows)
    lines.append("};")
    lines.append("inline constexpr CombiningClass kCombiningClasses[] = {")
    for start in range(0, len(classes), 6):
        lines.append("    " + " ".join(f"{{0x{cp:X}, {ccc}}}," for cp, ccc in classes[start:start + 6]))
    lines.append("};")
    lines.append("inline constexpr Composition kCompositions[] = {")
    for start in range(0, len(compositions), 4):
        lines.append("    " + " ".join(f"{{0x{a:X}, 0x{b:X}, 0x{c:X}}},"
                                        for a, b, c in compositions[start:start + 4]))
    lines.append("};")
    lines.append("// clang-format on")
    return "\n".join(lines) + "\n"


def golden_bytes() -> bytes:
    root = os.environ.get("OPENWHISPER_CPP_OW_ROOT")
    if not root:
        sys.exit("Set OPENWHISPER_CPP_OW_ROOT to the OpenWhisper checkout.")
    return (Path(root) / GOLDEN_SOURCE).read_bytes()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if unicodedata.unidata_version != EXPECTED_UNIDATA:
        sys.exit(f"unicodedata {unicodedata.unidata_version}; run this with Python 3.12 "
                 f"(Unicode {EXPECTED_UNIDATA}).")
    outputs = {NFKC_OUTPUT: nfkc_tables().encode("utf-8"), GOLDEN_OUTPUT: golden_bytes()}
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.is_file() or path.read_bytes() != content:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    for path in stale:
        print(f"{path.relative_to(ROOT)} is out of date; run tools/gen/bench_data.py")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
